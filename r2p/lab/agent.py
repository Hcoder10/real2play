REPLY_SCHEMA = {"type": "object", "properties": {
    "thought": {"type": "string"}, "plan": {"type": "string"},
    "calls": {"type": "array", "items": {"type": "object", "properties": {
        "tool": {"type": "string"}, "args": {"type": "object"}}, "required": ["tool", "args"]}},
    "done": {"type": "boolean"}, "why": {"type": "string"}},
    "required": ["thought", "calls", "done", "why"]}


class StatefulGemini(gemini.Gemini):
    """Use Interactions server state without modifying the shared Gemini transport."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.previous_interaction_id = None

    def _raw(self, parts, *, role, tag, config):
        config = {**config, "store": True}
        if self.previous_interaction_id:
            config["previous_interaction_id"] = self.previous_interaction_id
        text, record = super()._raw(parts, role=role, tag=tag, config=config)
        if record.get("interaction_id"):
            self.previous_interaction_id = record["interaction_id"]
        return text, record


def hidden_truth(workspace, task):
    """Private, isolated MuJoCo world. Its files and parameters never enter model tools."""
    import shutil
    import numpy as np
    from r2p.tasks import sample_scene
    temporary = tempfile.TemporaryDirectory(prefix="r2p-lab-truth-")
    directory = Path(temporary.name)
    shutil.copytree(MJCF.parent/"assets", directory/"robot_assets")
    physics = load_physics()
    for name, values in physics["joints"].items():
        values["kp"] *= .72
        values["kv"] *= 1.12
    physics["object"]["friction"] = .92
    scene = sample_scene(task, np.random.default_rng(706)) if task.get("objects") else {"objects": []}
    scene["table"] = {"color": "#876751", "friction": .92}
    for obj in scene.get("objects", []):
        obj["friction"] = .92
        obj["collide"] = True
    gemini.atomic_json(directory/"physics.json", physics)
    (directory/"scene.xml").write_text(initial_xml(workspace.camera, physics, scene), encoding="utf-8")
    sim = Simulation(directory, camera=workspace.camera)
    sim.hidden = True
    sim._temporary = temporary  # retains isolated truth assets until explicit close / process exit
    return sim


class LabAgent:
    def __init__(self, run, task, *, client=None, real_mock=False, approve="ask", input_fn=input,
                 managed_factory=ManagedAgent, backend=None):
        if approve not in ("ask", "auto-sim"):
            raise ValueError("approve must be ask or auto-sim")
        self.run, self.task = Path(run).resolve(), task
        self.run.mkdir(parents=True, exist_ok=True)
        self.ws = SimWorkspace(self.run, task)
        self.real_mock, self.approval = bool(real_mock), approve
        self.client = client or StatefulGemini(max_requests=40, timeout_s=180, retries=0)
        self.input_fn, self.managed_factory = input_fn, managed_factory
        backend = backend or (hidden_truth(self.ws, task) if real_mock else RealBackend())
        self.harness = Harness(self.run, task, backend, approve=self._approve)
        self.results = []
        self.history = []
        self.status = {"schema": "r2p_lab/1", "task": task.get("name", "task"), "status": "ready",
                       "real_mock": real_mock, "turn": 0, "model": "gemini-4-argon"}
        self.server = None
        self._publish()

    def _publish(self):
        gemini.atomic_json(self.run/"status.json", {**self.status, "updated": time.time(),
                                                  "latest_replay": self.ws.latest_replay})

    def _approve(self, primitives):
        if self.real_mock:
            return True
        if self.approval == "auto-sim":
            return False
        print("Real arm experiment requires owner approval for this call:\n"+json.dumps(primitives, indent=2), flush=True)
        return self.input_fn("Execute these real primitives? [y/N] ").strip().lower() == "y"

    def serve(self, port=8081):
        self.server = make_server(self.harness, ("127.0.0.1", port))
        self.server_thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.server_thread.start()
        return self.server.server_address

    def close(self):
        if self.server:
            self.server.shutdown()
            self.server.server_close()
            self.server_thread.join(timeout=3)
        temporary = getattr(self.harness.backend, "_temporary", None)
        if temporary:
            temporary.cleanup()

    def _crop(self, frame, box, path):
        p = confined(self.run, frame)
        if p.parts[len(self.run.parts)] not in ("episodes", "obs"):
            raise ValueError("Texture source must be an observation or training frame")
        if p.is_relative_to(self.run/"episodes") and p.relative_to(self.run/"episodes").parts[0] in self.ws.holdout["episodes"]:
            raise ValueError("Held-out pixels are not editable assets")
        image = cv2.imread(str(p))
        if image is None:
            raise ValueError("Texture source image missing")
        x0, y0, x1, y1 = map(int, box)
        if not 0 <= x0 < x1 <= image.shape[1] or not 0 <= y0 < y1 <= image.shape[0]:
            raise ValueError("Crop outside image")
        ok, data = cv2.imencode(Path(path).suffix, image[y0:y1, x0:x1])
        if not ok:
            raise ValueError("Texture encoding failed")
        return self.ws.edit_sim(path, base64.b64encode(data).decode(), encoding="base64")

    def managed_build(self, spec):
        sources = {}
        binary = {}
        total = 0
        for path in self.ws.directory.rglob("*"):
            if not path.is_file():
                continue
            relative = path.relative_to(self.ws.directory).as_posix()
            confined(self.ws.directory, relative)
            raw = path.read_bytes()
            total += len(raw)
            if total > 64_000_000:
                raise ValueError("Managed workspace exceeds 64 MB source budget")
            if path.suffix.lower() in (".xml", ".json", ".obj", ".mtl"):
                sources[relative] = raw.decode("utf-8")
            else:
                binary[relative] = base64.b64encode(raw).decode("ascii")
        if binary:
            sources["lab_binary_assets.json"] = json.dumps(binary)
        agent = self.managed_factory(source_files=sources, max_requests=20, timeout_s=300)
        bundle = agent.run("Build static MuJoCo assets for this specification. Do not access hardware or credentials. "
                           "No welds, equality, external forces, disabled collisions, qpos resets, executable output files. "
                           "Return JSON files/tests/report per the managed-agent contract. All asset paths relative to sim/. "
                           "Run any mesh generators in your sandbox and return resulting XML/JSON/OBJ only. "
                           "lab_binary_assets.json maps workspace-relative paths to base64 bytes; decode these locally "
                           "inside your sandbox before loading the scene. Do not return that transport file or robot meshes.\n"+spec,
                           tag="lab:managed_build")
        return {"validation": self.ws.edit_sim(files=bundle["files"]), "report": bundle["report"],
                "tests": bundle["tests"], "record": bundle["record"]}

    def call_tool(self, tool, args):
        mapping = {"obs": self.harness.obs, "real_plan": self.harness.plan, "sim_render": self.ws.sim_render,
                   "sim_plan": lambda primitives: self.ws.sim_plan(primitives, start_q=self.harness.backend.state()["q"]),
                   "read_sim": self.ws.read, "edit_sim": self.ws.edit_sim,
                   "replay": self.ws.replay, "reserve_holdout": self.ws.reserve_holdout, "score": self.ws.score,
                   "managed_build": self.managed_build, "crop_texture": self._crop}
        mapping.update(episode_frames=self.ws.episode_frames, label_episode=self.ws.label_episode)
        if tool not in mapping:
            raise ValueError("Unknown tool: "+str(tool))
        allowed = {"obs": set(), "real_plan": {"primitives", "split"}, "sim_render": {"camera"},
                   "sim_plan": {"primitives"}, "read_sim": {"path"},
                   "edit_sim": {"path", "content", "files", "encoding"}, "replay": {"episode", "object_reads"},
                   "reserve_holdout": {"episodes"}, "score": {"split"}, "managed_build": {"spec"},
                   "crop_texture": {"frame", "box", "path"}, "episode_frames": {"episode", "camera", "indices"},
                   "label_episode": {"episode", "object_reads"}}
        if not isinstance(args, dict) or set(args)-allowed[tool]:
            raise ValueError("Unrecognized tool arguments; internal evaluation overrides are not callable")
        return mapping[tool](**args)

    def turn(self, number):
        self._turn_evidence = {"turn": number, "time": time.time()}
        self.status.update(status="observing", turn=number)
        self._publish()
        obs = self.harness.obs()
        turn_dir = self.run/"turns"/str(number)
        turn_dir.mkdir(parents=True, exist_ok=True)
        for key in ("scene_cam_path", "wrist_cam_path"):
            destination = turn_dir/Path(obs[key]).name
            shutil.copy2(obs[key], destination)
            obs[key] = str(destination)
        self._turn_evidence["observation"] = deepcopy(obs)
        # Do not echo opaque episode results from held-out collection into fitting turns.
        if obs.get("last_episode") and obs["last_episode"].get("episode") in self.ws.holdout["episodes"]:
            obs["last_episode"] = {"heldout": True, "details_withheld": True}
        context = {"turn": number, "goal": self.task,
                   "instruction": "Make the sim match this real environment visually and physically for this task; "
                                  "experiment with the real arm as needed.",
                   "real_mock": self.real_mock, "approval": self.approval, "obs": obs,
                   "sim_files": self.ws.files(), "tool_results": self.results,
                   "latest_replay": self.ws.latest_replay, "history": self.history[-8:]}
        scope = ("This run is entirely a local CPU MuJoCo simulation. There is no physical robot connected. "
                 "The word real labels a private reference simulator.\n" if self.real_mock else "")
        if self.real_mock and number == 1:
            scope += "On this first dry turn, inspect scene.xml and physics.json and use sim_render to compare the views.\n"
        parts = [scope+TOOLS, json.dumps(context, default=gemini._json_default)]
        for key in ("scene_cam_path", "wrist_cam_path"):
            parts.extend([key, gemini.image_part(cv2.imread(obs[key]))])
        latest = self.ws.latest_replay
        if latest and latest.get("video"):
            parts.extend(["Latest real|sim replay, scene row then wrist row", gemini.video_part(latest["video"])])
        for result in self.results:
            image_path = result.get("result", {}).get("image")
            if image_path and Path(image_path).exists():
                parts.extend(["Tool render", gemini.image_part(cv2.imread(image_path))])
            for path in result.get("result", {}).get("images", []):
                parts.extend(["Independent episode observation: "+path, gemini.image_part(cv2.imread(path))])
            if result.get("tool") == "sim_plan":
                for key in ("video", "wrist_video"):
                    path = result.get("result", {}).get(key)
                    if path:
                        parts.extend(["Simulated rehearsal "+key, gemini.video_part(path)])
        self.status["status"] = "thinking"
        self._publish()
        started = time.monotonic()
        # Arbitrary tool args must not be sent as an empty-object response schema:
        # structured-output services otherwise erase their keys. Validate locally.
        text, record = self.client.call(parts, role="main", tag="lab:experiment", thinking="high",
                                       max_output_tokens=16000)
        self._turn_evidence.update(raw_response=text, record=record)
        response = gemini.parse_json(text)
        errors = gemini.schema_errors(response, REPLY_SCHEMA)
        if errors:
            raise ValueError("Invalid agent response: "+"; ".join(errors))
        if not response["thought"].startswith("# Thought:") or number == 1 and not response.get("plan", "").startswith("# Plan:"):
            raise ValueError("Argon must provide # Plan: on turn 1 and # Thought: every turn")
        print(response.get("plan", ""), flush=True)
        print(response["thought"], flush=True)
        self.results = []
        real_calls = 0
        for call in response["calls"]:
            self.status.update(status="tool", tool=call["tool"])
            self._publish()
            try:
                if call["tool"] == "real_plan":
                    real_calls += 1
                    if real_calls > 1:
                        raise ValueError("Re-observe visually on a new turn before another real_plan")
                value = self.call_tool(call["tool"], call["args"])
                result = {"tool": call["tool"], "result": value}
            except Exception as exc:
                result = {"tool": call["tool"], "error": gemini._safe(str(exc))}
            self.results.append(result)
            print(json.dumps({"tool": call["tool"], "result": "error" if "error" in result else "ok",
                              "error": result.get("error")}), flush=True)
        gate = self.ws.holdout.get("result", {})
        complete = bool(response["done"] and response["why"].strip() and gate.get("improved") and gate.get("sealed"))
        if response["done"] and not complete:
            self.results.append({"tool": "completion_gate", "error": "Done refused: need >=2 untouched held-out episodes, "
                                 "sealed improved physics+visual residuals, and Argon's statement"})
        entry = {"turn": number, "time": time.time(), "response": response, "results": self.results,
                 "record": record, "latency_s": time.monotonic()-started, "complete": complete}
        with (self.run/"ledger.jsonl").open("a", encoding="utf-8") as stream:
            stream.write(json.dumps(entry, default=gemini._json_default, allow_nan=False)+"\n")
        self.history.append({"turn": number, "thought": response["thought"], "calls": response["calls"]})
        self.status.update(status="complete" if complete else "running", complete=complete, why=response["why"],
                           heldout=gate or {"reserved": len(self.ws.holdout["episodes"])})
        self._publish()
        return entry

    def run_loop(self, max_turns=20):
        if not 1 <= max_turns <= 1000:
            raise ValueError("max_turns must be 1..1000")
        try:
            for i in range(1, max_turns+1):
                if self.turn(i)["complete"]:
                    return self.status
            self.status.update(status="incomplete", stop_reason="max_turns", complete=False)
            self._publish()
            return self.status
        except Exception as exc:
            self.status.update(status="error", error=gemini._safe(str(exc)), complete=False)
            entry = {**getattr(self, "_turn_evidence", {}), "error": gemini._safe(str(exc)), "complete": False}
            with (self.run/"ledger.jsonl").open("a", encoding="utf-8") as stream:
                stream.write(json.dumps(entry, default=gemini._json_default)+"\n")
            self._publish()
            raise


def fake_client(cache_dir):
    """A transparent offline smoke agent, never a fabricated live transcript."""
    responses = [{"thought": "# Thought: I need camera and baseline render evidence before editing.",
                  "plan": "# Plan: Inspect the basic twin, collect independent episodes, reserve two, then fit only training evidence.",
                  "calls": [{"tool": "sim_render", "args": {"camera": "scene"}},
                            {"tool": "real_plan", "args": {"primitives": [{"name": "done", "args": {}}]}}],
                  "done": False, "why": "Offline smoke test; no accuracy claim."}]
    return gemini.FakeGemini(responses, cache_dir=cache_dir)
